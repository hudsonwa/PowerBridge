"""Table of the tests a default pytest run does not run, grouped by reason.

Runs the default suite (pytest.ini's -m) on a copy of the working tree with no
native kernel (*.so / *.pyd left out) and PB_* variables unset, as on a fresh
clone, and records each deselected or skipped test. Prints a Markdown table, or
with --write replaces the block between the skip-report markers in
CONTRIBUTING.md.

With --native it keeps the built kernel and fills the skip-report-native block
instead: the run after tools/dev_setup.sh with a Rust toolchain present.

    python3 tools/skip_report.py [--native] [--write | --check]

--check exits 1 (printing a diff) when the table rows in CONTRIBUTING.md differ
from this run; CI runs it so the tables cannot drift.

Counts depend on the Python version and the optional tools installed (build,
setuptools), so the table records the interpreter it was made with.
"""
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(REPO, "CONTRIBUTING.md")
BEGIN = "<!-- skip-report: begin (generated by tools/skip_report.py; do not edit) -->"
END = "<!-- skip-report: end -->"
NATIVE_BEGIN = ("<!-- skip-report-native: begin "
                "(generated by tools/skip_report.py --native; do not edit) -->")
NATIVE_END = "<!-- skip-report-native: end -->"

# group -> (what it needs, whether public CI runs it). Groups are pytest markers
# or, for skips without a marker, the skip reason itself.
GROUPS = {
    "needs_captures": (
        "MultiCharts captures, audit tapes or the drawing corpus (licensed, not "
        "in the repo); `pytest -m needs_captures` with your data attached",
        "no"),
    "perf": ("a quiet machine; `PB_PERF=1 pytest -m perf`", "no"),
    "needs_native": (
        "the native kernel; `tools/build_accel.sh`, then a plain run",
        "yes: `accel-parity` (ci.yml) and `accel-macos-arm64` (accel.yml)"),
    "needs the 'build' module": (
        "`pip install -e '.[dev]'`", "no (the pytest job installs neither)"),
    "input name is an engine kwargs key": (
        "nothing: a parametrized case that does not apply (by design)", "n/a"),
    "no round trip": (
        "nothing: a ground-truth file outside the mirror dialect (by design)", "n/a"),
    "kernel refuses this program": (
        "nothing: a ground-truth program the native kernel does not support, so "
        "it runs in Python (by design)", "n/a"),
    "could not import 'numpy'": (
        "numpy (`pip install numpy`; not in the dev extra)", "no"),
    "private fixture absent": (
        "a licensed audit fixture; set `PB_AUDIT_FIXTURE_DIR` / `PB_AUDIT_EL`", "no"),
}

# Skip reasons that vary per test (the detail after the colon); counted as one row.
_COLLAPSE = ("kernel refuses this program", "private fixture absent",
             "could not import 'numpy'")
# Runtime skips (no marker) that belong to a marker's row.
_AS_MARKER = {"native kernel not built": "needs_native"}


def describe(group):
    """(needs, CI) for a group, matching skip reasons by prefix."""
    for key, value in GROUPS.items():
        if group == key or group.startswith(key):
            return value
    return ("see the skip reason", "no")

_MARKERS = ("needs_captures", "perf", "needs_native")

PLUGIN = r'''
import json, os
_out = os.environ["SKIP_REPORT_OUT"]
_rows = []
_GROUPED = tuple(os.environ["SKIP_REPORT_GROUPED"].split(","))

def _group(keywords, reason):
    for m in _GROUPED:
        if m in keywords:
            return m
    return reason

def pytest_deselected(items):
    for it in items:
        _rows.append(["deselected", _group(it.keywords, "deselected")])

def pytest_runtest_logreport(report):
    if report.skipped and report.when in ("setup", "call"):
        r = report.longrepr
        reason = str(r[2]) if isinstance(r, tuple) and len(r) == 3 else str(r)
        if reason.startswith("Skipped: "):
            reason = reason[len("Skipped: "):]
        _rows.append(["skipped", _group(report.keywords, reason.strip())])

def pytest_sessionfinish(session):
    import importlib.util
    try:
        kernel = importlib.util.find_spec("pl_transpiler._accel") is not None
    except ImportError:
        kernel = False
    with open(_out, "w") as f:
        json.dump({"rows": _rows, "kernel": kernel}, f)
'''


def collect(native=False):
    """[(how, group)] from a default pytest run on a copy of the tree, kernel-free
    unless native."""
    import json
    files = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=REPO,
                           capture_output=True, text=True, check=True).stdout.splitlines()
    if native:
        # The built kernel is git-ignored, so ls-files does not list it.
        pkg = os.path.join(REPO, "pl_transpiler")
        files += ["pl_transpiler/" + n for n in sorted(os.listdir(pkg))
                  if n.startswith("_accel") and n.endswith((".so", ".pyd"))]
    with tempfile.TemporaryDirectory() as tmp:
        tree = os.path.join(tmp, "tree")
        for rel in files:
            src = os.path.join(REPO, rel)
            if (not native and rel.endswith((".so", ".pyd"))) or not os.path.isfile(src):
                continue
            dst = os.path.join(tree, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
        with open(os.path.join(tmp, "skip_report_plugin.py"), "w") as f:
            f.write(PLUGIN)
        out = os.path.join(tmp, "rows.json")
        env = {k: v for k, v in os.environ.items() if not k.startswith("PB_")}
        # With the kernel built, needs_native skips have their own reasons.
        grouped = ("needs_captures", "perf") if native else _MARKERS
        env.update(SKIP_REPORT_OUT=out, SKIP_REPORT_GROUPED=",".join(grouped),
                   PYTHONPATH=tmp, PYTHONDONTWRITEBYTECODE="1")
        subprocess.run([sys.executable, "-m", "pytest", "-q", "--timeout=60",
                        "-p", "skip_report_plugin", "-p", "no:cacheprovider"],
                       cwd=tree, env=env, stdout=subprocess.DEVNULL)
        with open(out) as f:
            result = json.load(f)
    # An editable install or a stray kernel elsewhere on sys.path would make the
    # run test a different setup than the table claims.
    if result["kernel"] != native:
        raise SystemExit("skip_report: the pytest run %s the native kernel; expected "
                         "it %s" % ("found" if result["kernel"] else "did not find",
                                    "built" if native else "absent"))
    return [tuple(r) for r in result["rows"]]


def _collapse(group):
    for prefix, marker in _AS_MARKER.items():
        if group.startswith(prefix):
            return marker
    for prefix in _COLLAPSE:
        if group.startswith(prefix):
            return prefix
    return group


def table(rows, native=False):
    counts = Counter((how, _collapse(group)) for how, group in rows)
    lines = ["| Reason | Tests | Default run | Needs | Public CI runs it |",
             "| --- | ---: | --- | --- | --- |"]
    for (how, group), n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        needs, ci = describe(group)
        name = f"`{group}`" if group in _MARKERS else group.replace("|", "\\|")
        lines.append(f"| {name} | {n} | {how} | {needs} | {ci} |")
    py = "%d.%d" % sys.version_info[:2]
    lines.append("")
    kernel = "native kernel built" if native else "no native kernel"
    lines.append(f"Generated with Python {py} on {platform.system()}, {kernel}.")
    return "\n".join(lines)


def _rows_only(text):
    """The table lines, without the 'Generated with' note (it names the host)."""
    return [line for line in text.splitlines() if line.startswith("|")]


def check(text, begin, end):
    """0 if CONTRIBUTING.md's block has the same rows as this run, else 1."""
    import difflib
    with open(TARGET, encoding="utf-8") as f:
        doc = f.read()
    m = re.search(re.escape(begin) + r"(.*?)" + re.escape(end), doc, flags=re.S)
    if m is None:
        print(f"skip-report markers not found in {TARGET}", file=sys.stderr)
        return 1
    want, got = _rows_only(m.group(1)), _rows_only(text)
    if want == got:
        print("skip report matches CONTRIBUTING.md")
        return 0
    print("CONTRIBUTING.md skip report is out of date; regenerate it with "
          "tools/skip_report.py --write (see CONTRIBUTING.md):", file=sys.stderr)
    sys.stderr.writelines(difflib.unified_diff(
        [w + "\n" for w in want], [g + "\n" for g in got],
        "CONTRIBUTING.md", "this run"))
    return 1


def main(argv):
    native = "--native" in argv
    if native:
        import importlib.util
        sys.path.insert(0, REPO)
        if importlib.util.find_spec("pl_transpiler._accel") is None:
            print("--native needs the kernel built; run tools/build_accel.sh",
                  file=sys.stderr)
            return 1
    begin, end = (NATIVE_BEGIN, NATIVE_END) if native else (BEGIN, END)
    text = table(collect(native), native)
    if "--check" in argv:
        return check(text, begin, end)
    if "--write" not in argv:
        print(text)
        return 0
    with open(TARGET, encoding="utf-8") as f:
        doc = f.read()
    new, n = re.subn(re.escape(begin) + r".*?" + re.escape(end),
                     lambda _m: begin + "\n\n" + text + "\n\n" + end, doc, flags=re.S)
    if n != 1:
        print(f"skip-report markers not found in {TARGET}", file=sys.stderr)
        return 1
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(new)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
