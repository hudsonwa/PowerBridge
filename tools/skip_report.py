"""Table of the tests a default pytest run does not run, grouped by reason.

Runs the default suite (pytest.ini's -m) on a copy of the working tree with no
native kernel (*.so / *.pyd left out) and PB_* variables unset, as on a fresh
clone, and records each deselected or skipped test. Prints a Markdown table, or
with --write replaces the block between the skip-report markers in
CONTRIBUTING.md.

    python3 tools/skip_report.py [--write]

Counts depend on the Python version and the optional tools installed (build,
setuptools), so the table records the interpreter it was made with.
"""
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(REPO, "CONTRIBUTING.md")
BEGIN = "<!-- skip-report: begin (generated by tools/skip_report.py; do not edit) -->"
END = "<!-- skip-report: end -->"

# group -> (what it needs, whether public CI runs it). Groups are pytest markers
# or, for skips without a marker, the skip reason itself.
GROUPS = {
    "needs_captures": (
        "MultiCharts captures, audit tapes or the drawing corpus (licensed, not "
        "in the repo); `pytest -m needs_captures` with your data attached",
        "no"),
    "perf": ("a quiet machine; `PB_PERF=1 pytest -m perf`", "no"),
    "needs_native": (
        "the native kernel; `tools/build_accel.sh`, then a plain run",
        "yes: `accel-parity` (ci.yml) and `accel-macos-arm64` (accel.yml)"),
    "needs the 'build' module": (
        "`pip install -e '.[dev]'`", "no (the pytest job installs neither)"),
    "input name is an engine kwargs key": (
        "nothing: a parametrized case that does not apply (by design)", "n/a"),
    "no round trip": (
        "nothing: a ground-truth file outside the mirror dialect (by design)", "n/a"),
}


def describe(group):
    """(needs, CI) for a group, matching skip reasons by prefix."""
    for key, value in GROUPS.items():
        if group == key or group.startswith(key):
            return value
    return ("see the skip reason", "no")

_MARKERS = ("needs_captures", "perf", "needs_native")

PLUGIN = r'''
import json, os
_out = os.environ["SKIP_REPORT_OUT"]
_rows = []
_GROUPED = ("needs_captures", "perf", "needs_native")

def _group(keywords, reason):
    for m in _GROUPED:
        if m in keywords:
            return m
    return reason

def pytest_deselected(items):
    for it in items:
        _rows.append(["deselected", _group(it.keywords, "deselected")])

def pytest_runtest_logreport(report):
    if report.skipped and report.when in ("setup", "call"):
        r = report.longrepr
        reason = str(r[2]) if isinstance(r, tuple) and len(r) == 3 else str(r)
        if reason.startswith("Skipped: "):
            reason = reason[len("Skipped: "):]
        _rows.append(["skipped", _group(report.keywords, reason.strip())])

def pytest_sessionfinish(session):
    with open(_out, "w") as f:
        json.dump(_rows, f)
'''


def collect():
    """[(how, group)] from a default pytest run on a kernel-free copy of the tree."""
    import json
    files = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=REPO,
                           capture_output=True, text=True, check=True).stdout.splitlines()
    with tempfile.TemporaryDirectory() as tmp:
        tree = os.path.join(tmp, "tree")
        for rel in files:
            src = os.path.join(REPO, rel)
            if rel.endswith((".so", ".pyd")) or not os.path.isfile(src):
                continue
            dst = os.path.join(tree, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
        with open(os.path.join(tmp, "skip_report_plugin.py"), "w") as f:
            f.write(PLUGIN)
        out = os.path.join(tmp, "rows.json")
        env = {k: v for k, v in os.environ.items() if not k.startswith("PB_")}
        env.update(SKIP_REPORT_OUT=out, PYTHONPATH=tmp, PYTHONDONTWRITEBYTECODE="1")
        subprocess.run([sys.executable, "-m", "pytest", "-q", "--timeout=60",
                        "-p", "skip_report_plugin", "-p", "no:cacheprovider"],
                       cwd=tree, env=env, stdout=subprocess.DEVNULL)
        with open(out) as f:
            return [tuple(r) for r in json.load(f)]


def table(rows):
    counts = Counter(rows)
    lines = ["| Reason | Tests | Default run | Needs | Public CI runs it |",
             "| --- | ---: | --- | --- | --- |"]
    for (how, group), n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        needs, ci = describe(group)
        name = f"`{group}`" if group in _MARKERS else group.replace("|", "\\|")
        lines.append(f"| {name} | {n} | {how} | {needs} | {ci} |")
    py = "%d.%d" % sys.version_info[:2]
    lines.append("")
    lines.append(f"Generated with Python {py} on {platform.system()}, no native kernel.")
    return "\n".join(lines)


def main(argv):
    text = table(collect())
    if "--write" not in argv:
        print(text)
        return 0
    with open(TARGET, encoding="utf-8") as f:
        doc = f.read()
    new, n = re.subn(re.escape(BEGIN) + r".*?" + re.escape(END),
                     lambda _m: BEGIN + "\n\n" + text + "\n\n" + END, doc, flags=re.S)
    if n != 1:
        print(f"skip-report markers not found in {TARGET}", file=sys.stderr)
        return 1
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(new)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
