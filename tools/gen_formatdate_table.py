"""gen_formatdate_table.py — write the FormatDate table the native unit test checks.

Each row is ``(fmt, dt, pl_formatdate(fmt, dt))`` from the Python runtime, the
spec the native port in ``accel/src/strategy/datefmt.rs`` must match. Rerun
after changing ``_rt_datetime._fmt_dt`` or ``_decode_dt_yyyymmdd``::

    python tools/gen_formatdate_table.py
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from pl_transpiler.runtime.pl_runtime import pl_formatdate  # noqa: E402

OUT = REPO / "accel/src/strategy/fixtures/formatdate_table.txt"

FORMATS = [
    "yyyy-MM-dd HH:mm:ss", "dddd, MMMM d, yyyy", "ddd MMM dd yy", "M/d/y",
    "hh:mm:ss tt", "h:m:s t", "H.fff", "yyyyy MMMMM ddddd", "ffff",
    "dd/MM/yyyy hh:mm tt", "plain text, no tokens!", "", "été yyyy",
    "HHmmss", "tt t h hh", "Ms dy",
]
DATES = [
    # YYYYMMDD.frac bar DateTimes
    20240115.0, 20240229.5, 20231231.999994, 20000101.25, 20240704.0000057870,
    20240704.00000578704, 19991231.75, 20240310.041666666, 20241101.5416666,
    # serial DateTimes (days since 1899-12-30)
    0.0, 1.0, 45000.5, 45000.999999, 2.0000057870370, -1.25, -5.75, 36526.0,
    60.0, 61.0, 2958465.0, -693593.0, 45292.0208333, 45292.9895833,
    # round-half-even of the seconds
    45000.0 + 0.5 / 86400, 45000.0 + 1.5 / 86400, 45000.0 + 2.5 / 86400,
]


def main():
    rows = []
    for i, dt in enumerate(DATES):
        for fmt in (FORMATS[i % len(FORMATS)], FORMATS[(i + 5) % len(FORMATS)]):
            rows.append((fmt, dt, pl_formatdate(fmt, dt)))
    for fmt in FORMATS:
        rows.append((fmt, 20240115.6, pl_formatdate(fmt, 20240115.6)))
    lines = ["// Generated by tools/gen_formatdate_table.py; do not edit.", "&["]
    for fmt, dt, want in rows:
        lines.append(f"    ({json.dumps(fmt, ensure_ascii=False)}, {dt!r}, "
                     f"{json.dumps(want, ensure_ascii=False)}),")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT.name}")


if __name__ == "__main__":
    main()
