"""catalog.py — a small, documented query API over PowerBridge's EL keyword catalogs.

The catalogs are PowerBridge's own data; no third-party reference material ships
with the project (see NOTICE). Two machine-readable files are exposed as a
query surface:

  * ``pl_transpiler/tools/pl_signatures.jsonl`` — one JSON object per line, each with
    ``keyword``, ``returns``, ``min_arity``, and ``zero_arg_property``, plus the
    fields ``kind``, ``arg_types``, ``max_arity``, ``verification`` and ``verified_by``
    generated by ``tools/gen_catalog_fields.py`` from PowerBridge's own code and tests
    (null where PowerBridge cannot establish a value). Record shape:
    ``pl_transpiler/tools/pl_signatures.schema.json``.
  * ``pl_transpiler/tools/mc_verified_builtins.txt`` — one token per line (blank lines
    and ``#`` comments ignored), listing builtins known to compile in MultiCharts.

Two different "verified" notions — do not confuse them:

  * ``verification`` (a field of the shipped record; ``verification()``) is the
    evidence level PowerBridge has for its own behaviour on the keyword: ``n/a`` for
    syntax words, ``verified:capture-strategy`` (used by a strategy whose per-bar
    outputs (required columns) match a MultiCharts capture in tests/verify_all.py — the captures are not
    public, so that check skips in a clone, and the keyword's own value is not checked
    in isolation), ``verified:test`` or ``documented-unverified``.
  * ``verified`` (a bool that ``get()`` adds to the returned copy; ``is_verified()``)
    only says the name is on ``mc_verified_builtins.txt`` — known to compile in
    MultiCharts. It says nothing about PowerBridge's behaviour. It keeps its name
    because shipped tests and docs read ``get(name)["verified"]``.

Both files are read via ``importlib.resources`` so the API works identically from an
installed wheel and from a source checkout. All counts are DERIVED from the data at
load time — nothing is hardcoded.

Library usage::

    from pl_transpiler import catalog
    catalog.get("CurrentDate")          # -> record dict (case-insensitive) or None
    catalog.arity("CurrentDate")        # -> (0, True): min_arity, zero_arg_property
    catalog.returns("CurrentDate")      # -> "numeric"
    catalog.max_arity("Power")          # -> 2 (None if unknown)
    catalog.arg_types("Power")          # -> ["numeric", "numeric"] (None if unknown)
    catalog.kind("If")                  # -> "syntax" ("builtin" otherwise)
    catalog.verification("CurrentDate") # -> "verified:capture-strategy"
    catalog.is_verified("datetime")     # -> True
    catalog.search("date")              # -> sorted list of matching keyword names
    catalog.coverage()                  # -> {'signatures': N, 'verified_builtins': M, ...}

CLI::

    python -m pl_transpiler.catalog <name>
    python -m pl_transpiler.catalog --search <substring>
    python -m pl_transpiler.catalog --coverage
"""
from __future__ import annotations

import json
import sys
from importlib import resources
from typing import Any, Optional, cast

_TOOLS_PACKAGE = "pl_transpiler.tools"
_SIGNATURES_RESOURCE = "pl_signatures.jsonl"
_BUILTINS_RESOURCE = "mc_verified_builtins.txt"

# Lazily populated caches (keyed by lower-cased name for case-insensitive lookup).
_signatures: Optional[dict[str, dict[str, Any]]] = None          # dict: lower-name -> record dict (record['keyword'] is original case)
_verified_builtins: Optional[frozenset[str]] = None   # frozenset of lower-cased verified builtin tokens


def _read_resource(name: str) -> str:
    """Read a shipped data file as text, from a wheel or a checkout."""
    return resources.files(_TOOLS_PACKAGE).joinpath(name).read_text(encoding="utf-8")


def _load_signatures() -> dict[str, dict[str, Any]]:
    global _signatures
    if _signatures is None:
        recs = {}
        for line in _read_resource(_SIGNATURES_RESOURCE).splitlines():
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            recs[rec["keyword"].lower()] = rec
        _signatures = recs
    return _signatures


def _load_verified_builtins() -> frozenset[str]:
    global _verified_builtins
    if _verified_builtins is None:
        toks = set()
        for line in _read_resource(_BUILTINS_RESOURCE).splitlines():
            # Match mc_ground_check.py's parse: text before the first '#', stripped.
            tok = line.split("#", 1)[0].strip().lower()
            if tok:
                toks.add(tok)
        _verified_builtins = frozenset(toks)
    return _verified_builtins


def get(name: str) -> Optional[dict[str, Any]]:
    """Return the signature record dict for ``name`` (case-insensitive), or None.

    The returned dict is a copy of the shipped record augmented with a derived
    ``verified`` bool (True iff the keyword is on the MC-verified-builtin list). That
    bool is unrelated to the record's ``verification`` level; see the module docstring."""
    rec = _load_signatures().get(name.lower())
    if rec is None:
        return None
    out = dict(rec)
    out["verified"] = name.lower() in _load_verified_builtins()
    return out


VERIFICATION_LEVELS = ("verified:capture-strategy", "verified:test", "documented-unverified", "n/a")
KINDS = ("syntax", "builtin")


def arity(name: str) -> tuple[int, bool]:
    """Return ``(min_arity, zero_arg_property)`` for ``name`` (case-insensitive).

    Raises KeyError with a helpful message if the keyword is not in the signature
    catalog."""
    rec = _record(name)
    return (rec["min_arity"], rec["zero_arg_property"])


def _record(name: str) -> dict[str, Any]:
    rec = _load_signatures().get(name.lower())
    if rec is None:
        raise KeyError(
            f"{name!r} is not in the EL signature catalog "
            f"({len(_load_signatures())} keywords). Try catalog.search(...) "
            f"to find a similar name."
        )
    return rec


def returns(name: str) -> str:
    """Return the declared return type of ``name`` (case-insensitive).

    Raises KeyError with a helpful message if the keyword is not in the catalog."""
    return cast(str, _record(name)["returns"])


def arg_types(name: str) -> Optional[list[str]]:
    """Return the per-argument types of ``name`` (each numeric/any),
    or None when PowerBridge cannot establish them. Raises KeyError if unknown."""
    types = _record(name)["arg_types"]
    return None if types is None else list(types)


def max_arity(name: str) -> Optional[int]:
    """Return the largest argument count ``name`` accepts, or None when unknown.
    Raises KeyError if the keyword is not in the catalog."""
    return cast(Optional[int], _record(name)["max_arity"])


def kind(name: str) -> str:
    """Return ``"syntax"`` for a language/reserved or filler word, else ``"builtin"``.
    Raises KeyError if the keyword is not in the catalog."""
    return cast(str, _record(name)["kind"])


def verification(name: str) -> str:
    """Return how ``name`` is backed by evidence: ``"verified:capture-strategy"`` (used
    by a strategy whose per-bar outputs (required columns) match a MultiCharts capture
    in tests/verify_all.py; captures not public, so the check skips in a clone),
    ``"verified:test"`` (EL embedded in a PowerBridge test calls it),
    ``"documented-unverified"``, or ``"n/a"`` for syntax words.
    Raises KeyError if the keyword is not in the catalog."""
    return cast(str, _record(name)["verification"])


def is_verified(name: str) -> bool:
    """True iff ``name`` (case-insensitive) is an MC-verified builtin."""
    return name.lower() in _load_verified_builtins()


def search(substring: str) -> list[str]:
    """Return the sorted list of keyword names containing ``substring`` (case-insensitive)."""
    needle = substring.lower()
    sigs = _load_signatures()
    return sorted(rec["keyword"] for low, rec in sigs.items() if needle in low)


def coverage() -> dict[str, int]:
    """Return derived catalog counts.

    Keys:
      * ``signatures`` — number of keyword signature records.
      * ``verified_builtins`` — number of MC-verified builtin tokens.
      * ``verified_with_signature`` — verified builtins that also have a signature record.
      * ``kind:<kind>`` — signature records of each kind (``syntax``, ``builtin``).
      * ``verification:<level>`` — signature records at each verification level
        (``verified:capture-strategy``, ``verified:test``, ``documented-unverified``,
        ``n/a``).
      * ``with_max_arity`` — signature records whose ``max_arity`` is known.
    All values are computed from the data files, never hardcoded."""
    sigs = _load_signatures()
    verified = _load_verified_builtins()
    out = {
        "signatures": len(sigs),
        "verified_builtins": len(verified),
        "verified_with_signature": len(verified & set(sigs.keys())),
    }
    for k in KINDS:
        out[f"kind:{k}"] = 0
    for level in VERIFICATION_LEVELS:
        out[f"verification:{level}"] = 0
    out["with_max_arity"] = 0
    for rec in sigs.values():
        out[f"kind:{rec['kind']}"] += 1
        out[f"verification:{rec['verification']}"] += 1
        out["with_max_arity"] += rec["max_arity"] is not None
    return out


def _main(argv: Optional[list[str]] = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        prog="python -m pl_transpiler.catalog",
        description="Query the distilled EL keyword catalog.",
    )
    ap.add_argument("name", nargs="?", help="keyword to look up (prints its record)")
    ap.add_argument("--search", metavar="SUB", help="list keywords containing SUB")
    ap.add_argument("--coverage", action="store_true", help="print derived catalog counts")
    args = ap.parse_args(argv)

    if args.coverage:
        cov = coverage()
        print(f"signatures: {cov['signatures']}")
        print(f"verified_builtins: {cov['verified_builtins']}")
        print(f"verified_with_signature: {cov['verified_with_signature']}")
        for k in KINDS:
            print(f"kind {k}: {cov['kind:' + k]}")
        for level in VERIFICATION_LEVELS:
            print(f"verification {level}: {cov['verification:' + level]}")
        print(f"with_max_arity: {cov['with_max_arity']}")
        return 0

    if args.search is not None:
        names = search(args.search)
        for n in names:
            print(n)
        print(f"({len(names)} match{'' if len(names) == 1 else 'es'})")
        return 0

    if args.name:
        rec = get(args.name)
        if rec is None:
            print(f"{args.name!r} not found in the signature catalog.", file=sys.stderr)
            return 1
        print(json.dumps(rec, indent=2, sort_keys=True))
        return 0

    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(_main())
